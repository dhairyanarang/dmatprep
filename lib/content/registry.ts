import figureSequences from '@/content/sections/figure-sequences/questions.json'
import mathematicalEquations from '@/content/sections/mathematical-equations/questions.json'
import latinSquares from '@/content/sections/latin-squares/questions.json'

import { guide as figureGuide } from '@/content/sections/figure-sequences/guide'
import { guide as mathGuide } from '@/content/sections/mathematical-equations/guide'
import { guide as latinGuide } from '@/content/sections/latin-squares/guide'

import type { SectionId } from '@/lib/sections'
import type { SectionGuide } from '@/lib/types/content'
import type { Question } from '@/lib/types/question'

/**
 * Single lookup point for section content.
 *
 * The banks are generated by `scripts/generate` and validated by
 * `scripts/verify-bank.mjs`, which is where the real guarantees come from — the
 * cast here just gives the app the narrow types JSON import can't infer.
 */
const ALL: Record<SectionId, Question[]> = {
  'figure-sequences': figureSequences as unknown as Question[],
  'mathematical-equations': mathematicalEquations as unknown as Question[],
  'latin-squares': latinSquares as unknown as Question[],
}

/**
 * A quarantined question tests a mechanic we can no longer support from the
 * official material. It stays in the file and stays resolvable by id, because
 * attempts are immutable and an attempt that can no longer name its question is
 * a broken record. What it must not do is reach a pool again, so every servable
 * path reads `BANKS` and only `getQuestion` reads `ALL`.
 *
 * Not retirement: retirement reserves an id forever. If a future re-date of the
 * preparatory PDF documents the mechanic, these come back by deleting a field.
 */
const isQuarantined = (q: Question) => q.meta?.quarantined != null

const BANKS: Record<SectionId, Question[]> = {
  'figure-sequences': ALL['figure-sequences'].filter((q) => !isQuarantined(q)),
  'mathematical-equations': ALL['mathematical-equations'].filter((q) => !isQuarantined(q)),
  'latin-squares': ALL['latin-squares'].filter((q) => !isQuarantined(q)),
}

const GUIDES: Record<SectionId, SectionGuide> = {
  'figure-sequences': figureGuide,
  'mathematical-equations': mathGuide,
  'latin-squares': latinGuide,
}

export function getGuide(sectionId: SectionId): SectionGuide {
  return GUIDES[sectionId]
}

export function getQuestions(sectionId: SectionId): Question[] {
  return BANKS[sectionId]
}

/**
 * Everything that answers a question or teaches the answer.
 *
 * Kept in step with `SOLUTION_KEYS` in scripts/build-solutions.mjs, which writes
 * the other half. `scripts/test/answer-delivery.test.mjs` fails if the two lists
 * disagree — a field stripped here but not written there would be lost, and one
 * written there but not stripped here would still ship with the page.
 */
const SOLUTION_KEYS = [
  'correctOptionId',
  'explanation',
  'distractorNotes',
  'walkthrough',
  'solutionSteps',
  'solution',
  'rules',
] as const

/**
 * A question as a candidate should first meet it: stem, options, panels, grid
 * and hints, with nothing that answers it.
 *
 * Every practice route serves these rather than the full records. The solutions
 * are fetched separately — see `lib/solutions/use-solutions.ts` — so a candidate
 * who has not answered has not been handed the answer in the page they are
 * reading. Hints stay: they are pre-answer content by design, and `verify-bank`
 * already fails any hint that contains the answer.
 *
 * This is hygiene rather than protection. The solution files are static assets
 * and anyone can fetch them. That is the right level for the Core bank, which is
 * free; it is not the right level for anything sold.
 */
export type PublicQuestion = Omit<Question, (typeof SOLUTION_KEYS)[number]>

export function getPublicQuestions(sectionId: SectionId): PublicQuestion[] {
  return BANKS[sectionId].map(stripSolution)
}

function stripSolution(question: Question): PublicQuestion {
  const copy = { ...question } as Record<string, unknown>
  for (const key of SOLUTION_KEYS) delete copy[key]

  // Figure Sequences carries its key inside each image rather than on the
  // question, so the generic strip above does not reach it.
  if (question.kind === 'figure-sequence') {
    copy.images = question.images.map((image) => {
      const rest: Record<string, unknown> = { ...image }
      delete rest.correctOptionId
      return rest
    })
  }
  return copy as unknown as PublicQuestion
}

/**
 * Resolves quarantined questions too — a stored attempt must always be able to
 * name what it was an attempt at. Callers that render a question to be answered
 * want `getQuestions`.
 */
export function getQuestion(sectionId: SectionId, id: string): Question | undefined {
  return ALL[sectionId].find((q) => q.id === id)
}

export function getBankSize(sectionId: SectionId): number {
  return BANKS[sectionId].length
}
