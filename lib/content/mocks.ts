import coreMocks from '@/content/access/core-mocks.json'

import { getPublicQuestions, type PublicQuestion } from '@/lib/content/registry'
import { SECTION_BY_ID, SECTION_IDS, type SectionId } from '@/lib/sections'

/**
 * The four fixed Core mock exams.
 *
 * Fixed is the whole point. The practice runner plans a session from a pool at
 * run time, ranking by what you have already seen, so it gives a different
 * test on every visit — right for practice, wrong for a mock. Two attempts at
 * "Core mock 2" have to be the same test or their scores are not comparable,
 * which is the only thing a mock score is for.
 *
 * So the question lists are a committed artefact generated by
 * `scripts/build-core-mocks.mjs`, never recomputed in the app. This module only
 * resolves ids to records.
 */

export type CoreMock = {
  id: string
  label: string
  number: number
  sections: Record<SectionId, string[]>
}

const SETS = coreMocks.sets as { id: string; label: string; sections: Record<string, string[]> }[]

export const MOCKS_PER_SECTION = coreMocks.questionsPerSection as number

export function getCoreMocks(): CoreMock[] {
  return SETS.map((set, i) => ({
    id: set.id,
    label: set.label,
    number: i + 1,
    sections: set.sections as Record<SectionId, string[]>,
  }))
}

export function getCoreMock(id: string): CoreMock | undefined {
  return getCoreMocks().find((m) => m.id === id)
}

/** Total questions in one mock — derived, never written down twice. */
export function mockSize(mock: CoreMock): number {
  return SECTION_IDS.reduce((n, s) => n + (mock.sections[s]?.length ?? 0), 0)
}

export type MockStage = {
  sectionId: SectionId
  label: string
  unitNoun: string
  pool: PublicQuestion[]
  count: number
  questionIds: string[]
}

const UNIT: Record<SectionId, string> = {
  'figure-sequences': 'series',
  'mathematical-equations': 'systems',
  'latin-squares': 'tasks',
}

/**
 * The stages for one mock, in the documented subtest order.
 *
 * The pool handed over is the whole section rather than just this mock's
 * twenty, because the launcher also uses it to rebuild a resumed session — and
 * a session saved mid-mock has to find its questions somewhere.
 */
export function mockStages(mock: CoreMock): MockStage[] {
  return SECTION_IDS.map((sectionId) => ({
    sectionId,
    label: SECTION_BY_ID[sectionId].title,
    unitNoun: UNIT[sectionId],
    pool: getPublicQuestions(sectionId),
    count: mock.sections[sectionId]?.length ?? 0,
    questionIds: mock.sections[sectionId] ?? [],
  }))
}
