#!/usr/bin/env node
/**
 * Point the walkthrough and the level-2 hint at the equation the collapse
 * actually happens in.
 *
 * THE DEFECT. `solveOrder` used to pick the equation to cite as "the first one
 * with two or more letters", which is frequently a plain definition rather than
 * the line anything collapses into. Fourteen questions already on `main` tell
 * the candidate to "substitute the other equations into `3 × D + 2 = B`" — a
 * definition OF B — when the collapse happens in `A + C = 12`. The answer, the
 * options, the solution steps and the stated value were all correct; only the
 * equation named was wrong, in two places: the first walkthrough step and the
 * level-2 hint.
 *
 * The generator was fixed in 4.1.2 (a combining equation is identified by its
 * numeric right-hand side). This repairs the items already committed.
 *
 * WHY NOT REBUILD FROM THE SEED, as the b10/b12 repair does. These items were
 * generated by 3.0.0 to 3.3.0. Rebuilding them under 4.1.2 would hand them a
 * slot target they never had and produce different questions. So this edits the
 * two narrated strings in place and touches nothing else — no equation, option,
 * key, solution step, difficulty, id or provenance is written at all.
 *
 * WHAT IS PROVEN BEFORE ANYTHING IS WRITTEN, per item:
 *
 *   1. The replacement equation is one of the item's own, with a numeric
 *      right-hand side.
 *   2. Fixing the named letter to each value in 1..20 and solving the OTHER
 *      equations leaves exactly one assignment that satisfies the replacement
 *      equation, and it is the stored solution. That is what "leaves X as the
 *      only unknown" asserts, so it is checked rather than assumed — and it is
 *      checked with this file's own solver, not the generator's.
 *   3. The value the step states is the stored value of that letter.
 *   4. After the edit, the question differs from before ONLY in
 *      walkthrough.steps[0] and hints[1].
 *
 *   node scripts/repair/me-cited-equation.mjs [--dry-run]
 */
import { readFileSync, writeFileSync } from 'node:fs'

const dryRun = process.argv.includes('--dry-run')
const bankUrl = new URL('../../content/sections/mathematical-equations/questions.json', import.meta.url)
const bank = JSON.parse(readFileSync(bankUrl, 'utf8'))

/** The fourteen reported by the 22 November 2026 audit. */
const IDS = [
  'me-high-b2-004', 'me-high-b2-005', 'me-high-b4-005', 'me-medium-b5-018',
  'me-high-b5-003', 'me-high-b5-009', 'me-high-b5-010', 'me-high-b5-013',
  'me-high-b5-015', 'me-high-b5-017', 'me-high-b5-026', 'me-high-b5-028',
  'me-high-b5-029', 'me-high-b5-030',
]

/* ------------------------------- a solver of this file's own, for the proof */

const TIMES = '×', DIVIDE = '÷', MINUS = '−'

function parse(src) {
  const tok = []
  for (let i = 0; i < src.length;) {
    const c = src[i]
    if (c === ' ') { i++; continue }
    if (c >= '0' && c <= '9') { let j = i; while (j < src.length && src[j] >= '0' && src[j] <= '9') j++; tok.push({ t: 'n', v: Number(src.slice(i, j)) }); i = j; continue }
    if (c >= 'A' && c <= 'Z') { tok.push({ t: 'v', v: c }); i++; continue }
    if ('+=()'.includes(c) || c === TIMES || c === DIVIDE || c === MINUS) { tok.push({ t: 'o', v: c }); i++; continue }
    throw new Error(`bad character ${JSON.stringify(c)} in "${src}"`)
  }
  let p = 0
  const peek = () => tok[p]
  const factor = () => {
    const t = tok[p]
    if (t.t === 'o' && t.v === '(') { p++; const e = expr(); p++; return e }
    p++
    return t.t === 'n' ? { k: 'n', v: t.v } : { k: 'v', v: t.v }
  }
  const term = () => { let n = factor(); while (peek() && peek().t === 'o' && (peek().v === TIMES || peek().v === DIVIDE)) { const o = tok[p++].v; n = { k: 'o', o, l: n, r: factor() } } return n }
  function expr() { let n = term(); while (peek() && peek().t === 'o' && (peek().v === '+' || peek().v === MINUS)) { const o = tok[p++].v; n = { k: 'o', o, l: n, r: term() } } return n }
  const lhs = expr(); p++; const rhs = expr()
  return { lhs, rhs }
}
const evaluate = (n, env) => {
  if (n.k === 'n') return n.v
  if (n.k === 'v') return env[n.v]
  const a = evaluate(n.l, env), b = evaluate(n.r, env)
  if (a === undefined || b === undefined) return undefined
  return n.o === '+' ? a + b : n.o === MINUS ? a - b : n.o === TIMES ? a * b : b === 0 ? undefined : a / b
}
const holds = (eq, env) => { const a = evaluate(eq.lhs, env), b = evaluate(eq.rhs, env); return a !== undefined && b !== undefined && Math.abs(a - b) < 1e-9 }

/**
 * Does fixing `letter` leave the rest determined, and does exactly one value of
 * it satisfy `combining`? Brute force over 1..20 — small, and owes nothing to
 * the generator.
 */
function collapsesTo(equations, letters, combining, letter) {
  const others = equations.filter((e) => e !== combining).map(parse)
  const comb = parse(combining)
  const rest = letters.filter((l) => l !== letter)
  const winners = []
  for (let v = 1; v <= 20; v++) {
    const assignments = []
    const env = { [letter]: v }
    const rec = (i) => {
      if (assignments.length > 1) return
      if (i === rest.length) { if (others.every((e) => holds(e, env))) assignments.push({ ...env }); return }
      for (let w = 1; w <= 20; w++) { env[rest[i]] = w; rec(i + 1) }
      delete env[rest[i]]
    }
    rec(0)
    if (assignments.length === 1 && holds(comb, assignments[0])) winners.push(assignments[0])
  }
  return winners
}

/* ----------------------------------------------------------------- repair */

const refusals = []
const done = []

for (const id of IDS) {
  const q = bank.find((x) => x.id === id)
  if (!q) { refusals.push(`${id}: not in the bank`); continue }

  const before = JSON.stringify(q)
  const step = q.walkthrough?.steps?.[0]
  const hint2 = (q.hints || []).find((h) => h.level === 2)
  if (!step || !hint2) { refusals.push(`${id}: no first step or no level-2 hint`); continue }

  const cited = (step.detail.match(/into (.+?) leaves/) || [])[1]
  const named = (step.detail.match(/leaves ([A-Z]) as the only unknown/) || [])[1]
  const statedValue = Number((step.detail.match(/which gives [A-Z] = (\d+)/) || [])[1])
  if (!cited || !named || !Number.isFinite(statedValue)) { refusals.push(`${id}: first step is not the substitution shape`); continue }

  // the combining equation: numeric right-hand side, widest
  const numeric = q.equations.filter((e) => /= \d+$/.test(e))
  const combining = [...numeric].sort((a, b) =>
    new Set(b.match(/[A-Z]/g) || []).size - new Set(a.match(/[A-Z]/g) || []).size)[0]
  if (!combining) { refusals.push(`${id}: no equation with a numeric right-hand side`); continue }
  if (combining === cited) { refusals.push(`${id}: already cites the combining equation — nothing to repair`); continue }

  // ---- PROOF, before anything is written
  if (statedValue !== q.solution[named]) { refusals.push(`${id}: step states ${named} = ${statedValue} but the solution has ${q.solution[named]}`); continue }
  // NOT a requirement that the letter appear literally in the equation. In
  // me-high-b5-028 the collapse is `D − B + C = 16` with D, B and C all defined
  // from A: substituting gives 4A = 16, so A is the only unknown without ever
  // being written in that line. The collapse proof below is the real test and
  // it covers this case; a literal-containment check would reject it wrongly.
  const winners = collapsesTo(q.equations, q.variables, combining, named)
  if (winners.length !== 1) { refusals.push(`${id}: fixing ${named} does not leave the rest determined (${winners.length} values work)`); continue }
  if (winners[0][named] !== q.solution[named]) { refusals.push(`${id}: the collapse gives ${named} = ${winners[0][named]}, not ${q.solution[named]}`); continue }
  for (const [k, v] of Object.entries(q.solution)) {
    if (winners[0][k] !== v) { refusals.push(`${id}: collapse disagrees on ${k}`); break }
  }

  // ---- the edit: the equation NAMED, nothing else
  step.detail = step.detail.replace(`into ${cited} leaves`, `into ${combining} leaves`)
  if (step.visual && step.visual.equation === cited) step.visual.equation = combining

  /**
   * A HINT MAY NOT CONTAIN THE ANSWER, and quoting the right equation can break
   * that rule where the walkthrough cannot.
   *
   * me-high-b2-005 asks for C and the answer is 6; the equation the collapse
   * happens in is `D + B = 6`. Naming it in the hint would put the answer on the
   * page before the candidate has solved anything — `verify-bank` catches this
   * and rejected the first run of this repair, which is the gate doing its job.
   *
   * So where the equation's own text carries the answer value, the hint
   * describes the line instead of quoting it. The generator already does exactly
   * this when quoting would reveal the answer (`quotingWouldReveal` in
   * buildHints), so this follows the established shape rather than inventing one.
   * The walkthrough still quotes the equation, which is correct: it is only shown
   * after the question has been answered.
   */
  const answerValue = q.options.find((o) => o.id === q.correctOptionId)?.value
  const quotingRevealsAnswer =
    answerValue !== undefined &&
    new RegExp(`(^|[^0-9])${answerValue}([^0-9]|$)`).test(combining)

  hint2.text = quotingRevealsAnswer
    ? 'Do not start from a line that defines one letter in terms of another — those are what you substitute. Find the one whose right-hand side is a plain number, and push the others into it.'
    : hint2.text.split(cited).join(combining)

  if (answerValue !== undefined && new RegExp(`(^|[^0-9])${answerValue}([^0-9]|$)`).test(hint2.text)) {
    refusals.push(`${id}: the repaired level-2 hint still contains the answer ${answerValue}`)
    continue
  }

  // ---- confirm only the two narrated strings moved
  const after = JSON.parse(JSON.stringify(q))
  const original = JSON.parse(before)
  const originalStep = original.walkthrough.steps[0]
  const originalHint = original.hints.find((h) => h.level === 2)
  originalStep.detail = step.detail
  if (originalStep.visual) originalStep.visual.equation = step.visual?.equation ?? originalStep.visual.equation
  originalHint.text = hint2.text
  if (JSON.stringify(original) !== JSON.stringify(after)) {
    refusals.push(`${id}: the edit changed something beyond the first step and the level-2 hint`)
    continue
  }

  done.push(`${id}: ${cited}  ->  ${combining}`)
}

if (refusals.length) {
  console.error('REFUSED — nothing written:')
  for (const r of refusals) console.error(`  ${r}`)
  process.exit(1)
}

console.log(`${done.length} item(s) ${dryRun ? 'would be' : ''} repaired`)
for (const d of done) console.log(`  ${d}`)
if (!dryRun && done.length) {
  writeFileSync(bankUrl, `${JSON.stringify(bank, null, 2)}\n`)
  console.log('\nwritten. Now run: npm run build:solutions && npm run verify:bank')
}
