#!/usr/bin/env node
/**
 * The human-review package for Module B.
 *
 *   npm run review:package
 *
 * Everything a person needs to sign off — or refuse — each active GAM pack, in
 * one file: the full source text, every question with its options and key, the
 * explanation and the refutation for each wrong option, the provenance and
 * validation status, and every finding on record against it.
 *
 * Generated, not written, so it cannot drift from the packs it describes. It is
 * a reviewer's view and shows answer keys throughout; it is not a candidate's
 * view and is not a route.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'

import { contentHash } from './lib/validate.mjs'

const base = new URL('../../content/gam/', import.meta.url)
const packsDir = new URL('packs/', base)
const adjudications = JSON.parse(readFileSync(new URL('review/adjudications.json', base), 'utf8'))
const flags = JSON.parse(readFileSync(new URL('review/review-flags.json', base), 'utf8'))

/** The round in force for a pack: complete, not superseded, and bound to this content. */
function roundFor(file) {
  const hash = contentHash(file)
  return adjudications.rounds
    .filter((r) => r.status === 'complete' && !r.supersededOn)
    .find((r) => r.adjudicatedContent?.[file.pack.id] === hash)
}

const files = readdirSync(packsDir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(readFileSync(new URL(f, packsDir), 'utf8')))
  .filter((f) => !f.pack.provenance?.retiredOn)
  .sort((a, b) => a.pack.domain.localeCompare(b.pack.domain))

const out = []
const W = (s = '') => out.push(s)

const renderBlock = (b) => {
  if (b.kind === 'heading') return `**${b.text}**`
  if (b.kind === 'paragraph') return b.text
  if (b.kind === 'table') {
    const head = `| ${b.columns.join(' | ')} |`
    const rule = `|${b.columns.map(() => '---').join('|')}|`
    return [`*${b.caption}*`, '', head, rule, ...b.rows.map((r) => `| ${r.join(' | ')} |`)].join('\n')
  }
  if (b.kind === 'figure') {
    const s = b.spec ?? {}
    const series = (s.series ?? [])
      .map((x) => `  · ${x.label}: ${(x.points ?? []).map((p) => `(${p[0]}, ${p[1]})`).join('  ')}`)
      .join('\n')
    return [`*${b.caption}*`, '', '```', `${s.type ?? 'figure'} — x: ${s.xLabel ?? '?'} · y: ${s.yLabel ?? '?'}`, series, '```'].join('\n')
  }
  return JSON.stringify(b)
}

/* --------------------------------------------------------------- summary */

const sourceIndependent = []
const leaking = []
let active = 0

for (const file of files) {
  const round = roundFor(file)
  for (const q of file.questions) {
    active++
    const rec = round?.questions?.[q.id]
    if (rec?.evidence?.ablationVerdict === 'determinable') sourceIndependent.push(q.id)
    if (rec?.evidence?.ablationLeaks) leaking.push({ id: q.id, severity: rec.evidence.ablationLeakSeverity })
  }
}

W('# Module B — human review package')
W()
W(`Generated by \`npm run review:package\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`)
W()
W('**Nothing in here is signed off.** Every pack below is blocked on exactly this review.')
W('Automated validation and two independent blind model rounds are evidence about these')
W('questions; they are not a person taking responsibility for putting them in front of a')
W('candidate. Answer keys are shown throughout because this is a reviewer’s view.')
W()
W('## What you are being asked to decide, per pack')
W()
W('1. Is every keyed answer right?')
W('2. Is there exactly one defensible answer, on the source as written?')
W('3. Does the source do real work, or would a well-prepared candidate answer without it?')
W('4. Are the recorded couplings acceptable, or must the questions change?')
W('5. Ship it, change it, or withdraw it.')
W()
W('## Summary')
W()
W(`| | |`)
W(`|---|---|`)
W(`| Active packs | ${files.length} |`)
W(`| Active questions | ${active} |`)
W(`| **Answerable with no source at all** | **${sourceIndependent.length} of ${active}** |`)
W(`| Carrying a recorded coupling | ${leaking.length} of ${active} |`)
W(`| Signed off by a person | **0 of ${files.length}** |`)
W()
W('### The questions a candidate could answer without reading the source')
W()
W('This is the finding that matters most, and no amount of distractor editing reaches it.')
W('An adjudicator shown the stem and options with no source at all answered each of these')
W('confidently. A pack built of them tests what a candidate already knows, not whether they')
W('can read.')
W()
for (const id of sourceIndependent) W(`- \`${id}\``)
W()
W('### Questions carrying a recorded coupling')
W()
for (const l of leaking) W(`- \`${l.id}\` — ${l.severity}`)
W()
W('---')

/* ----------------------------------------------------------- each pack */

for (const file of files) {
  const round = roundFor(file)
  W()
  W(`## ${file.pack.title}`)
  W()
  W(`\`${file.pack.id}\` · domain **${file.pack.domain}** · ${file.questions.length} questions`)
  W()
  W(round
    ? `Adjudicated by round \`${round.id}\` (${round.adjudicator?.model ?? 'unrecorded'}).`
    : '**No qualifying adjudication round covers this pack as it now stands.**')
  if (round?.caveat) {
    W()
    W('> **Caveat on every figure from that round.** ' + round.caveat)
  }
  const packFlag = flags.packFlags?.[file.pack.id]
  if (packFlag?.length) {
    W()
    W('**Pack-level findings**')
    W()
    for (const f of packFlag) W(`- *${f.flag}* — ${f.reason}`)
  }
  W()
  W('### Source material, in full')
  W()
  W('This is everything the candidate is given. If a question cannot be answered from what')
  W('follows, it is defective however plausible its key looks.')
  W()
  for (const b of file.pack.blocks) {
    W(`<a id="${file.pack.id}-${b.id}"></a>**[${b.id}]** ${renderBlock(b)}`)
    W()
  }

  for (const q of file.questions) {
    const rec = round?.questions?.[q.id]
    const qFlags = flags.questionFlags?.[q.id] ?? []
    const keyed = q.options.find((o) => o.id === q.correctOptionId)
    W('---')
    W()
    W(`### \`${q.id}\``)
    W()
    W(`> ${q.stem}`)
    W()
    for (const o of q.options) {
      const mark = o.id === q.correctOptionId ? ' ← **KEY**' : ''
      W(`- **(${o.id})** ${o.text}${mark}`)
    }
    W()
    W(`**Why the key is the key.** ${q.explanation}`)
    W()
    if (q.refutations && Object.keys(q.refutations).length) {
      W('**Why each other option is wrong**')
      W()
      for (const [id, r] of Object.entries(q.refutations)) {
        W(`- **(${id})** — *${r.family}*, from \`${r.blockId}\`: ${r.reason}`)
      }
      W()
    }
    W('**Which source blocks it rests on:** ' + (q.dependsOn ?? []).map((b) => `\`${b}\``).join(', ') || '*none recorded*')
    W()
    if (q.supportSpans?.length) {
      W('**The phrases it rests on**')
      W()
      for (const s of q.supportSpans) W(`- \`${s.blockId}\`: "${s.quote}"`)
      W()
    }
    W('**Validation and provenance**')
    W()
    W('| | |')
    W('|---|---|')
    W(`| Blind adjudicator chose | ${rec ? `\`${rec.chosenOption}\` — ${rec.chosenOption === q.correctOptionId ? '**agrees with the key**' : '**DISAGREES WITH THE KEY**'}` : '*not adjudicated*'} |`)
    W(`| Exactly one defensible option | ${rec?.exactlyOneDefensibleOption === true ? 'yes' : rec ? '**no**' : '—'} |`)
    W(`| Needs knowledge the source does not give | ${rec?.requiresOutsideKnowledge === true ? '**yes**' : rec ? 'no' : '—'} |`)
    W(`| Source does real work | ${rec?.sourceMateriallyContributes === true ? 'yes' : rec ? '**no**' : '—'} |`)
    W(`| Recognition rather than transfer | ${rec?.recognitionNotTransfer === true ? 'yes' : rec ? 'no' : '—'} |`)
    W(`| Dependency class | ${rec?.dependency ?? '—'} |`)
    W(`| **Answerable with NO source** | ${rec?.evidence?.ablationVerdict === 'determinable' ? `**yes** — would have chosen \`${rec.evidence.ablationWouldChoose}\` at ${rec.evidence.ablationConfidence} confidence` : rec ? 'no' : '—'} |`)
    W(`| Coupling to a sibling | ${rec?.evidence?.ablationLeaks ? `**${rec.evidence.ablationLeakSeverity}**, by ${(rec.evidence.ablationLeakedBy ?? []).join(', ')}` : rec ? 'none found' : '—'} |`)
    W()
    if (rec?.evidence?.ablationLeaks && rec.evidence.ablationLeakDetail) {
      W('**How the coupling works**')
      W()
      W('> ' + rec.evidence.ablationLeakDetail.replace(/\n+/g, '\n> '))
      W()
    }
    if (qFlags.length) {
      W('**Open flags**')
      W()
      for (const f of qFlags) W(`- *${f.flag}* (${f.severity}) — ${f.reason}`)
      W()
    }
  }

  const retired = file.pack.provenance?.retiredQuestions ?? []
  if (retired.length) {
    W('---')
    W()
    W(`### Withdrawn from this pack (${retired.length})`)
    W()
    for (const r of retired) {
      W(`**\`${r.id}\`** — withdrawn ${r.retiredOn}`)
      W()
      W('> ' + r.reason)
      W()
    }
  }
}

writeFileSync(new URL('review/HUMAN_REVIEW.md', base), out.join('\n'))
console.log(`wrote content/gam/review/HUMAN_REVIEW.md`)
console.log(`  ${files.length} active packs, ${active} questions`)
console.log(`  ${sourceIndependent.length} answerable with no source: ${sourceIndependent.join(', ')}`)
console.log(`  ${leaking.length} carrying a coupling`)
