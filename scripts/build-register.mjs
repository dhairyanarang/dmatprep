#!/usr/bin/env node
/**
 * The content register: every active, quarantined and retired item, with its
 * status, provenance and outstanding review requirement.
 *
 *   npm run register
 *
 * Generated rather than maintained by hand, so it cannot drift from the bank it
 * describes. Writes JSON for machines and Markdown for people; both are
 * committed so a reviewer can read the state without running anything.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'

import { readBank, readRetired, SECTIONS } from './lib/bank.mjs'
import { verifyQuestion } from './lib/verify.mjs'
import { classify } from './lib/provenance.mjs'

const rows = []

for (const section of SECTIONS) {
  for (const q of readBank(section)) {
    const { errors, warnings } = verifyQuestion(q)
    const derived = classify(q)
    const quarantined = q.meta?.quarantined
    rows.push({
      id: q.id,
      module: 'Core',
      section,
      status: quarantined ? 'quarantined' : 'active',
      difficulty: q.difficulty,
      alignment: q.meta?.dmatAlignment,
      provenance: derived.provenance,
      validation: {
        errors: errors.length,
        warnings: warnings.length,
        uniqueSolutionProved: errors.length === 0,
      },
      outstanding: quarantined ? quarantined.reason : null,
    })
  }
  for (const entry of readRetired(section)) {
    rows.push({
      id: entry.id ?? entry.question?.id,
      module: 'Core',
      section,
      status: 'retired',
      difficulty: entry.question?.difficulty ?? null,
      alignment: null,
      provenance: null,
      validation: null,
      outstanding: entry.reason ?? null,
    })
  }
}

/* ------------------------------------------------------------------- GAM */

const packsDir = new URL('../content/gam/packs/', import.meta.url)
const reviewUrl = new URL('../content/gam/review/adjudications.json', import.meta.url)
const adjudications = existsSync(reviewUrl) ? JSON.parse(readFileSync(reviewUrl, 'utf8')) : { rounds: [] }
const current = adjudications.rounds.filter((r) => r.status === 'complete' && !r.supersededOn).at(-1)

for (const file of readdirSync(packsDir).filter((f) => f.endsWith('.json'))) {
  const pack = JSON.parse(readFileSync(new URL(file, packsDir), 'utf8'))
  const retiredPack = Boolean(pack.pack.provenance?.retiredOn)

  for (const q of pack.questions) {
    const rec = current?.questions?.[q.id]
    const leak = rec?.evidence?.ablationLeaks
      ? `${rec.evidence.ablationLeakSeverity} coupling, leaked by ${(rec.evidence.ablationLeakedBy ?? []).join(', ')}`
      : null
    rows.push({
      id: q.id,
      module: 'GAM',
      section: pack.pack.domain,
      status: retiredPack ? 'retired' : 'active',
      difficulty: q.difficulty ?? null,
      alignment: null,
      provenance: rec ? { dependency: rec.dependency, blindAgreed: rec.chosenOption === q.correctOptionId } : null,
      validation: rec
        ? { exactlyOneDefensibleOption: rec.exactlyOneDefensibleOption, requiresOutsideKnowledge: rec.requiresOutsideKnowledge }
        : null,
      outstanding: retiredPack
        ? 'pack retired'
        : [leak, 'not signed off by a person'].filter(Boolean).join('; '),
    })
  }

  for (const r of pack.pack.provenance?.retiredQuestions ?? []) {
    rows.push({
      id: r.id,
      module: 'GAM',
      section: pack.pack.domain,
      status: 'retired',
      difficulty: null,
      alignment: null,
      provenance: null,
      validation: null,
      outstanding: r.reason ?? null,
    })
  }
}

/* ---------------------------------------------------------------- output */

const tally = {}
for (const r of rows) {
  const key = `${r.module}/${r.status}`
  tally[key] = (tally[key] ?? 0) + 1
}

writeFileSync(
  new URL('../audit/content-register.json', import.meta.url),
  `${JSON.stringify({ generatedAt: new Date().toISOString().slice(0, 10), tally, rows }, null, 2)}\n`,
)

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const md = [
  '# Content register',
  '',
  `Generated by \`npm run register\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
  '',
  '| count | |',
  '|---|---|',
  ...Object.entries(tally).sort().map(([k, v]) => `| ${k} | ${v} |`),
  '',
  '## Every item',
  '',
  '| id | module | section | status | alignment | errors | outstanding |',
  '|---|---|---|---|---|---|---|',
  ...rows.map(
    (r) =>
      `| ${r.id} | ${r.module} | ${r.section} | ${r.status} | ${esc(r.alignment ?? r.provenance?.dependency ?? '—')} | ${r.validation?.errors ?? '—'} | ${esc((r.outstanding ?? '—').slice(0, 160))} |`,
  ),
  '',
].join('\n')
writeFileSync(new URL('../audit/content-register.md', import.meta.url), md)

console.log(`${rows.length} items registered`)
for (const [k, v] of Object.entries(tally).sort()) console.log(`  ${k.padEnd(20)} ${v}`)
