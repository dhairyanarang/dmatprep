/**
 * Per-question verification, shared by generation and `verify-bank`.
 *
 * This used to live inside `verify-bank.mjs`, which meant generation and
 * verification could drift: the Phase 3 audit's central finding was that Figure
 * Sequence validation only ever asked "does the stored rule produce the stored
 * answer", never "do the shown matrices imply one continuation". Now there is
 * one implementation and both callers use it, so a gate cannot be enforced in
 * one place and forgotten in the other.
 *
 * ## Errors vs warnings
 *
 * Two checks are new and strict enough that the pre-existing bank does not pass
 * them. They are hard errors for anything generated by the append-only pipeline
 * (batch b2 onward) and loud warnings for the legacy b1 bank, which the Phase 3
 * fix brief explicitly holds byte-for-byte fixed apart from two retirements.
 * This is deliberately *not* a loosening: no b1 item is wrong, the warnings are
 * printed on every run, and no new item can carry either defect.
 */
import { verifyLatinSquare } from '../generate/latin-squares.mjs'
import { parseEquation, satisfies, solveAll } from './equations.mjs'
import { panelsEqual, simulate } from './figures.mjs'
import { disambiguationErrors } from './fs-inversion.mjs'
import { equationContractErrors, figureRuleContractErrors, latinContractErrors, FS_CONTRACT } from './contract.mjs'
import { equationSkeleton } from './fingerprint.mjs'
import { classify } from './provenance.mjs'

const DIFFICULTIES = ['low', 'medium', 'high']

/** b1 predates append-only generation and carries no batch stamp. */
export const isLegacy = (q) => !q.generator?.batchId || q.generator.batchId === 'b1'

const cmpVersion = (a = '0.0.0', b = '0.0.0') => {
  const pa = String(a).split('.').map(Number)
  const pb = String(b).split('.').map(Number)
  for (let i = 0; i < 3; i++) if ((pa[i] ?? 0) !== (pb[i] ?? 0)) return (pa[i] ?? 0) - (pb[i] ?? 0)
  return 0
}

/**
 * Checks introduced with a generator fix are hard errors for anything that
 * generator version could have produced, and warnings for items made by an
 * earlier version. Same principle as the b1 legacy boundary: a new gate must
 * make recurrence impossible without retroactively failing a bank the brief
 * holds fixed.
 */
export const predates = (q, version) => cmpVersion(q.generator?.version, version) < 0

/**
 * Teaching content — explanations, distractor notes, hints — can be repaired
 * without regenerating the item it belongs to, so its currency is tracked
 * separately from the generator that built the equations.
 *
 * An item whose notes were rebuilt to a later generator's rules is held to that
 * generator's standard even though its `generator.version` still records what
 * produced the mathematics. Without this, a repair would land in the bank and
 * the very checks it satisfies would stay downgraded to warnings, so nothing
 * would stop the defect returning.
 */
export const teachingPredates = (q, version) =>
  cmpVersion(q.generator?.teachingContent?.version ?? q.generator?.version, version) < 0

function verifyCommon(q) {
  const errors = []
  if (!q.id) errors.push('missing id')
  if (!DIFFICULTIES.includes(q.difficulty)) errors.push(`bad difficulty: ${q.difficulty}`)
  if (!q.explanation || q.explanation.trim().length < 20) errors.push('missing or trivial explanation')
  if (!q.generator?.name) errors.push('missing generator stamp')

  // Everything the append-only pipeline produces must be reproducible in
  // isolation: section + tier + batchId + index + attempt + version + config.
  if (!isLegacy(q)) {
    const stamp = q.generator ?? {}
    for (const field of ['version', 'batchId', 'seed', 'seedCoordinates', 'config']) {
      if (stamp[field] === undefined) errors.push(`generator stamp is missing "${field}" — item is not reproducible`)
    }
    if (stamp.seedCoordinates && !Number.isInteger(stamp.seedCoordinates.attempt)) {
      errors.push('generator stamp records no accepted attempt index')
    }
  }
  return errors
}

function verifyLearningAids(q) {
  const errors = []

  if (q.hints) {
    const levels = q.hints.map((h) => h.level)
    if (levels.join(',') !== '1,2,3') errors.push(`hint levels are ${levels.join(',')}, expected 1,2,3`)
    for (const hint of q.hints) {
      if (!hint.text || hint.text.trim().length < 15) errors.push(`hint ${hint.level} is too thin`)
    }

    const text = q.hints.map((h) => h.text).join(' ')
    if (q.kind === 'math-equations') {
      const answer = q.solution[q.asked]
      if (new RegExp(`(^|[^0-9])${answer}([^0-9]|$)`).test(text)) {
        errors.push(`a hint contains the answer value ${answer}`)
      }
    }
    if (q.kind === 'latin-square') {
      if (new RegExp(`\\b${q.correctOptionId}\\b`).test(text)) {
        errors.push(`a hint names the answer letter ${q.correctOptionId}`)
      }
    }
    if (q.kind === 'figure-sequence' && /\bmatrix\s*[123]\b/i.test(text)) {
      errors.push('a hint names a specific answer option')
    }
  }

  if (q.walkthrough) {
    const w = q.walkthrough
    if (!w.keyInsight || w.keyInsight.length < 20) errors.push('walkthrough has no key insight')
    if (!Array.isArray(w.steps) || w.steps.length < 2) errors.push('walkthrough needs at least two steps')
    if (!w.answer) errors.push('walkthrough states no answer')
    if (!w.takeaway || w.takeaway.length < 20) errors.push('walkthrough has no takeaway')
    for (const step of w.steps ?? []) {
      if (!step.title || !step.detail) errors.push('a walkthrough step is missing its title or detail')
    }
    if (q.kind === 'math-equations' && !w.answer.includes(String(q.solution[q.asked]))) {
      errors.push('walkthrough answer disagrees with the solution')
    }
    if (q.kind === 'latin-square' && !w.answer.includes(q.correctOptionId)) {
      errors.push('walkthrough answer disagrees with correctOptionId')
    }
  }

  if (q.meta) {
    // `dmat_prep_calibration` ships: it says plainly that we chose the mechanic
    // and that the official material does not settle it. `uncertain` still
    // blocks, because it claims nothing either way.
    const allowed = [
      'officially_documented',
      'reasonable_extrapolation',
      'dmat_prep_calibration',
      'uncertain',
    ]
    if (!allowed.includes(q.meta.dmatAlignment)) errors.push(`unknown dmatAlignment: ${q.meta.dmatAlignment}`)

    // The grade must be the one the question earns. Without this, `dmatAlignment`
    // is a free-text field that anything can set to `officially_documented` —
    // which is exactly how all 473 came to claim it.
    if (q.meta.provenance) {
      const derived = classify(q)
      if (derived.dmatAlignment !== q.meta.dmatAlignment) {
        errors.push(
          `dmatAlignment is "${q.meta.dmatAlignment}" but this question derives "${derived.dmatAlignment}"`,
        )
      }
      for (const axis of ['format', 'answerFormat', 'mechanics', 'originality']) {
        if (q.meta.provenance[axis] !== derived.provenance[axis]) {
          errors.push(
            `provenance.${axis} is "${q.meta.provenance[axis]}" but derives "${derived.provenance[axis]}"`,
          )
        }
      }
    }
    if (q.meta.dmatAlignment === 'uncertain') {
      errors.push('an item classified `uncertain` must not ship without human review')
    }
    if (!Array.isArray(q.meta.patternType) || q.meta.patternType.length === 0) {
      errors.push('meta.patternType is empty')
    }
  }

  return errors
}

function verifyDistractorCoverage(q) {
  const errors = []
  const notes = q.distractorNotes ?? {}
  const expectKey = (key, label) => {
    if (!notes[key] || notes[key].trim().length < 10) errors.push(`no distractor note for ${label}`)
  }

  if (q.kind === 'figure-sequence') {
    for (const image of q.images) {
      for (const option of image.options) {
        if (option.id === image.correctOptionId) continue
        expectKey(`${image.label}:${option.id}`, `${image.label}/${option.id}`)
      }
    }
  } else {
    for (const option of q.options) {
      if (option.id === q.correctOptionId) continue
      expectKey(option.id, option.id)
    }
  }
  return errors
}

/* ---------------------------------------------------- Mathematical Equations */

/** Operators actually present, so a note cannot cite one the item does not use. */
export const operatorsIn = (equations) => new Set((equations.join(' ').match(/[+−×÷]/g) ?? []))

/**
 * A level-2 hint must not hand over an equation that is one arithmetic step from
 * the answer. The old mechanical check only forbade the answer *numeral*, so
 * `"Look at A ÷ 3 = 3."` passed for every one of the 15 low items while giving
 * the whole question away.
 */
export function hintRevealsAnswer(q) {
  const answer = q.solution?.[q.asked]
  for (const hint of q.hints ?? []) {
    const text = hint.text ?? ''

    // Quoting an equation that holds only the asked letter *is* the answer, one
    // arithmetic step away. This was checked at level 2 alone, which is where the
    // generator puts the quotation; a hint at any level does the same damage.
    const quoted = /Look at ([^.]+)\./.exec(text)
    if (quoted) {
      const letters = [...new Set(quoted[1].match(/[A-Z]/g) ?? [])]
      if (letters.length === 1 && letters[0] === q.asked) {
        return `level-${hint.level} hint quotes "${quoted[1]}", which contains only the asked letter — one step from the answer`
      }
    }

    // And no hint may simply state the solved value, however it is phrased.
    if (
      answer !== undefined &&
      new RegExp(`(^|[^0-9])${answer}([^0-9]|$)`).test(text) &&
      new RegExp(`\\b${q.asked}\\b`).test(text)
    ) {
      return `level-${hint.level} hint states ${q.asked} = ${answer}, which is the answer rather than a hint`
    }
  }
  return null
}

function verifyMathEquations(q) {
  const errors = []
  let parsed
  try {
    parsed = q.equations.map(parseEquation)
  } catch (e) {
    return { errors: [`unparseable equation: ${e.message}`], warnings: [] }
  }

  const solutions = solveAll(parsed, q.variables, 2)
  if (solutions.length === 0) errors.push('system has no solution over 1..20')
  if (solutions.length > 1) errors.push('system does not have a unique solution')

  if (solutions.length === 1) {
    for (const name of q.variables) {
      if (solutions[0][name] !== q.solution[name]) {
        errors.push(`stored ${name}=${q.solution[name]}, re-solved ${name}=${solutions[0][name]}`)
      }
    }
    const correct = q.options.find((o) => o.id === q.correctOptionId)
    if (!correct) errors.push('correctOptionId is not among the options')
    else if (correct.value !== solutions[0][q.asked]) {
      errors.push(`correct option is ${correct.value}, but ${q.asked} = ${solutions[0][q.asked]}`)
    }
  }

  const values = q.options.map((o) => o.value)
  if (new Set(values).size !== values.length) errors.push('duplicate option values')
  if (!q.variables.includes(q.asked)) errors.push(`asked letter ${q.asked} is not in the system`)
  if (!satisfies(parsed, q.solution)) errors.push('stored solution does not satisfy every equation')

  const answer = q.solution[q.asked]
  if (q.options.filter((o) => o.value === answer).length !== 1) {
    errors.push('the answer value does not appear on exactly one option')
  }

  errors.push(...equationContractErrors(q))

  for (const option of q.options) {
    if (option.id === q.correctOptionId) continue
    const note = q.distractorNotes[option.id]
    if (note && !note.startsWith(`${option.value} `)) {
      errors.push(`note for ${option.id} does not describe the value ${option.value}`)
    }
  }

  const warnings = []

  // A distractor note may only name an operation the system actually performs.
  //
  // Legacy note: 8 of the 45 b1 items carry a note blaming an operator their
  // system does not contain. These are genuine (if minor) factual errors in the
  // teaching copy, but the Phase 3 fix brief holds the b1 bank byte-identical
  // apart from two mandated retirements, so they surface as warnings pending an
  // approved wording correction. No newly generated item can carry one: the
  // generator only offers the family when the operator is present.
  const ops = operatorsIn(q.equations)
  for (const [id, family] of Object.entries(q.meta?.distractorTypes ?? {})) {
    const note = q.distractorNotes[id] ?? ''
    if (family !== 'inverted-operation') continue
    if (/multiply where the equation divides/.test(note) && !ops.has('÷')) {
      ;(teachingPredates(q, '3.1.0') ? warnings : errors).push(
        `note for ${id} blames division, but the system contains no ÷`,
      )
    }
    if (/divide where the equation multiplies/.test(note) && !ops.has('×')) {
      ;(teachingPredates(q, '3.1.0') ? warnings : errors).push(
        `note for ${id} blames multiplication, but the system contains no ×`,
      )
    }
  }

  if (q.meta?.distractorTypes) {
    const offByOne = Object.values(q.meta.distractorTypes).filter((f) => f === 'off-by-one').length
    if (offByOne > 1) errors.push(`${offByOne} off-by-one distractors; the policy allows one`)
  }

  // No official system repeats a left-hand side.
  const lhs = q.equations.map((e) => e.split(' = ')[0])
  if (new Set(lhs).size !== lhs.length) {
    ;(predates(q, '3.1.0') ? warnings : errors).push('two equations share a left-hand side')
  }

  // Distractor-note mechanism accuracy. Each family asserts *why* a value arises;
  // this checks the value actually arises that way. Added after the Phase 5 pilot
  // found `misapplied-constant` notes citing "the first equation" (wrong 9 times
  // out of 17) and asserting a mechanism that could not produce the number.
  for (const option of q.options) {
    if (option.id === q.correctOptionId) continue
    const family = q.meta?.distractorTypes?.[option.id]
    const note = q.distractorNotes[option.id] ?? ''
    const push = (m) => (teachingPredates(q, '3.1.0') ? warnings : errors).push(m)

    if (family === 'off-by-one' && Math.abs(option.value - answer) !== 1) {
      push(`${option.id} is labelled off-by-one but is ${option.value} against an answer of ${answer}`)
    }
    if (family === 'inverted-operation' && option.value !== answer * 2 && option.value !== answer / 2) {
      push(`${option.id} is labelled inverted-operation but is neither double nor half the answer`)
    }
    if (family === 'wrong-variable' || family === 'stopped-early') {
      const holder = Object.entries(q.solution).find(([n, v]) => n !== q.asked && v === option.value)
      if (!holder) push(`${option.id} claims to be another letter's value, but no letter holds ${option.value}`)
    }
    if (family === 'misapplied-constant') {
      const quoted = /from (.+?) by /.exec(note)
      if (/the first equation/.test(note)) {
        // The superseded note format. One finding, not two.
        push(`${option.id} refers to "the first equation"; equations are shuffled, so it must be named by its text`)
      } else if (!quoted) push(`${option.id} names no equation`)
      else if (!q.equations.includes(quoted[1])) {
        push(`${option.id} quotes "${quoted[1]}", which is not an equation in this system`)
      } else {
        // Re-run the stated mistake and confirm it lands on this option's value.
        const rhs = Number(quoted[1].split(' = ')[1])
        const how = /by (.+?)\. Undoing/.exec(note)?.[1] ?? ''
        let produced = null
        let m
        if ((m = /multiplying by (\d+) instead of dividing/.exec(how))) produced = rhs * Number(m[1])
        else if ((m = /dividing by (\d+) again/.exec(how))) produced = rhs / Number(m[1])
        else if ((m = /adding (\d+) instead of subtracting/.exec(how))) produced = rhs + Number(m[1])
        else if ((m = /subtracting (\d+) again/.exec(how))) produced = rhs - Number(m[1])
        else if ((m = /adding ([A-Z]) instead of subtracting/.exec(how))) produced = rhs + q.solution[m[1]]
        if (produced === null) push(`${option.id} states no recognisable mechanism`)
        else if (!Number.isFinite(rhs)) push(`${option.id} quotes an equation with no numeric right-hand side`)
        else if (produced !== option.value) {
          push(`${option.id}: "${how}" on ${quoted[1]} gives ${produced}, not ${option.value}`)
        }
      }
    }
  }

  const leak = hintRevealsAnswer(q)
  if (leak) (teachingPredates(q, '3.1.0') ? warnings : errors).push(leak)

  // A hint may only promise an operation to undo when there is one. A bare pin
  // (`C = 14`, official Example 1) has nothing on either side to undo, and the
  // generic phrasing told the candidate otherwise.
  const level2 = q.hints?.find((h) => h.level === 2)?.text ?? ''
  if (/undo that operation on both sides/.test(level2)) {
    const hasOperatedEquation = q.equations.some((e) => {
      const letters = new Set(e.match(/[A-Z]/g) ?? [])
      return letters.size === 1 && letters.has(q.asked) && /[+−×÷]/.test(e)
    })
    if (!hasOperatedEquation) {
      ;(predates(q, '3.3.0') ? warnings : errors).push(
        'level-2 hint says to undo an operation, but no equation applies one to the asked letter',
      )
    }
  }

  // And the answer must not simply be printed: an equation stating the asked
  // letter outright makes the item a reading exercise, not a reasoning one.
  if (q.equations.some((e) => e === `${q.asked} = ${answer}`)) {
    ;(predates(q, '3.3.0') ? warnings : errors).push(
      `an equation states ${q.asked} = ${answer} outright, so the answer is printed on the page`,
    )
  }

  return { errors, warnings }
}

/* --------------------------------------------------------- Figure Sequences */

function verifyFigureSequence(q) {
  const errors = []
  const warnings = []

  // Structural sanity before simulating: a malformed item must produce an error,
  // not an exception. `simulate` dereferences rules[id] unguarded.
  if (!Array.isArray(q.given) || q.given.length === 0 || !q.given[0]?.symbols?.length) {
    return { errors: ['item has no shown matrices'], warnings }
  }
  const missingRules = q.given[0].symbols.filter((s) => !q.rules?.[s.id]?.movement).map((s) => s.id)
  if (missingRules.length) {
    return { errors: [`no rule for symbol(s): ${missingRules.join(', ')}`], warnings }
  }

  const symbols = q.given[0].symbols.map((s) => ({
    ...s,
    direction: q.rules[s.id]?.movement?.direction ?? null,
  }))

  const panels = simulate(symbols, q.rules, 6)
  if (!panels) return { errors: ['re-simulation failed: a symbol leaves the grid or two overlap'], warnings }

  for (let i = 0; i < 4; i++) {
    if (!panelsEqual(panels[i], q.given[i])) errors.push(`given panel ${i + 1} does not match the rules`)
  }

  const expected = [panels[4], panels[5]]
  q.images.forEach((image, i) => {
    const correct = image.options.find((o) => o.id === image.correctOptionId)
    if (!correct) {
      errors.push(`${image.label}: correctOptionId missing from options`)
      return
    }
    if (!panelsEqual(correct.panel, expected[i])) {
      errors.push(`${image.label}: the marked answer is not the panel the rules produce`)
    }
    if (image.options.length !== 3) errors.push(`${image.label}: expected 3 options`)

    for (let a = 0; a < image.options.length; a++) {
      for (let b = a + 1; b < image.options.length; b++) {
        if (panelsEqual(image.options[a].panel, image.options[b].panel)) {
          errors.push(`${image.label}: options ${a + 1} and ${b + 1} are identical`)
        }
      }
    }
    for (const option of image.options) {
      if (option.id === image.correctOptionId) continue
      if (panelsEqual(option.panel, expected[i])) {
        errors.push(`${image.label}: distractor ${option.id} is also correct`)
      }
    }
  })

  if (q.given.length !== 4) errors.push(`expected 4 given matrices, found ${q.given.length}`)
  if (q.images.length !== 2) errors.push(`expected 2 images, found ${q.images.length}`)

  const symbolCount = q.given[0].symbols.length
  if (symbolCount > FS_CONTRACT.allowed.maxSymbols) {
    errors.push(`${symbolCount} symbols; the official exercises never exceed ${FS_CONTRACT.allowed.maxSymbols}`)
  }
  if (symbolCount < FS_CONTRACT.allowed.minSymbols) errors.push('an item must have at least one symbol')

  for (const [id, rule] of Object.entries(q.rules)) {
    for (const problem of figureRuleContractErrors(rule)) {
      // The legacy bank contains accelerating colour cycles, which are
      // REVIEW-class and unusable at attested lengths. Held as warnings for b1.
      ;(isLegacy(q) ? warnings : errors).push(`${id}: ${problem}`)
    }
  }

  const everyPanel = [...q.given, ...q.images.flatMap((im) => im.options.map((o) => o.panel))]
  for (const panel of everyPanel) {
    if (panel.symbols.length !== symbolCount) errors.push('a panel has a different symbol count')
    const cells = new Set()
    for (const s of panel.symbols) {
      if (s.cell.row < 0 || s.cell.row >= q.grid.rows || s.cell.col < 0 || s.cell.col >= q.grid.cols) {
        errors.push('a symbol sits outside the matrix')
      }
      const key = `${s.cell.row},${s.cell.col}`
      if (cells.has(key)) errors.push('two symbols overlap in a panel')
      cells.add(key)
    }
  }

  // THE gate: the shown matrices must imply exactly one continuation.
  for (const problem of disambiguationErrors(q.given, q.rules)) {
    ;(isLegacy(q) ? warnings : errors).push(problem)
  }

  const push = (m) => (isLegacy(q) || predates(q, '3.1.0') ? warnings : errors).push(m)

  // Every image must offer two distinct distractor families, and never two
  // positional nudges — a wrong panel that encodes no nameable error teaches
  // nothing, and two of them leave the image with nothing to learn from.
  //
  // A hard error for every item, legacy included: the eight items that carried
  // this were repaired or retired on 5 September 2026, so nothing in the bank
  // needs the exemption and leaving one open would let the defect back in. The
  // loop covers *both* predicted matrices — the earlier version of this rule
  // only required two families across the item as a whole, which let one image
  // ship two nudges as long as the other supplied the variety.
  for (const image of q.images) {
    const families = image.options
      .filter((o) => o.id !== image.correctOptionId)
      .map((o) => q.meta?.distractorTypes?.[`${image.label}:${o.id}`])
    if (families.length === 2 && families[0] && families[1]) {
      if (families[0] === families[1]) {
        errors.push(`${image.label}: both distractors are the same family (${families[0]})`)
      }
      if (families.every((f) => f === 'position')) {
        errors.push(`${image.label}: both distractors are the arbitrary positional nudge`)
      }
    }
  }

  // An explanation must describe the heading the candidate actually sees. A
  // symbol starting against a boundary in its nominal direction reverses before
  // matrix 1 is drawn, so the stored heading is never observed.
  for (const symbol of q.given[0].symbols) {
    const rule = q.rules[symbol.id]
    if (rule.movement.type !== 'diagonal') continue
    const a = q.given[0].symbols.find((x) => x.id === symbol.id).cell
    const b = q.given[1].symbols.find((x) => x.id === symbol.id).cell
    const dr = Math.sign(b.row - a.row)
    const dc = Math.sign(b.col - a.col)
    if (!dr || !dc) continue
    const observed = `${dr < 0 ? 'up' : 'down'}-${dc < 0 ? 'left' : 'right'}`
    const phrase = observed.replace('-', 'wards to the ')
    if (!q.explanation.includes(`moves diagonally ${phrase}`)) {
      push(
        `explanation does not describe the ${symbol.shape}'s observed heading (${observed}); it may be naming the pre-bounce internal heading`,
      )
    }
  }

  return { errors, warnings }
}

/* ------------------------------------------------------------- entry point */

export function verifyQuestion(q) {
  const errors = [...verifyCommon(q), ...verifyLearningAids(q), ...verifyDistractorCoverage(q)]
  const warnings = []

  if (q.kind === 'latin-square') {
    errors.push(...verifyLatinSquare(q), ...latinContractErrors(q))
  } else if (q.kind === 'math-equations') {
    const r = verifyMathEquations(q)
    errors.push(...r.errors)
    warnings.push(...r.warnings)
  } else if (q.kind === 'figure-sequence') {
    const r = verifyFigureSequence(q)
    errors.push(...r.errors)
    warnings.push(...r.warnings)
  }

  return { errors, warnings }
}

